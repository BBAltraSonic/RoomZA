import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const release = JSON.parse(fs.readFileSync(path.join(dir,'release.json')));
const require = createRequire(path.join(release.snapshot,'package.json'));
const { JSDOM } = require('jsdom');
const next = '/saved?tab=specials';
const pageUrl = new URL('/auth',release.origin);pageUrl.searchParams.set('redirect',next);
const response = await fetch(pageUrl,{signal:AbortSignal.timeout(30000)});
assert.equal(response.status,200);
const html = await response.text();
const document = new JSDOM(html).window.document;
const form = [...document.querySelectorAll('form')].find(item=>item.textContent.includes('Continue with Google'));
assert(form,'Google form missing');
assert.equal(form.querySelector('button').disabled,false,'Google button disabled');
assert(!form.textContent.includes('Coming soon'),'Coming soon label remains');
const body = new FormData();
for(const input of form.querySelectorAll('input[name]')) body.append(input.name,input.value);
assert.equal(body.get('redirect'),next);
assert([...body.keys()].some(key=>key.startsWith('$ACTION_')),'Server action metadata missing');
const started = await fetch(new URL(form.getAttribute('action')||pageUrl,release.origin),{
  method:'POST',body,headers:{Origin:release.origin},redirect:'manual',signal:AbortSignal.timeout(30000),
});
assert.equal(started.status,303,'Google server action did not redirect');
const authorize = new URL(started.headers.get('location'));
assert.equal(authorize.hostname,'qleeedwnnfvmfjjymoco.supabase.co');
assert.equal(authorize.searchParams.get('provider'),'google');
const appCallback = new URL(authorize.searchParams.get('redirect_to'));
assert.equal(appCallback.origin,release.origin);assert.equal(appCallback.pathname,'/auth/callback');
assert.equal(appCallback.searchParams.get('next'),next);
const verifierCookie = started.headers.getSetCookie().map(value=>value.split(';')[0]).find(value=>value.split('=')[0].endsWith('-code-verifier'));
assert(verifierCookie,'PKCE verifier cookie missing');
const cookieValue=decodeURIComponent(verifierCookie.slice(verifierCookie.indexOf('=')+1));
const verifier=JSON.parse(Buffer.from(cookieValue.slice('base64-'.length),'base64url').toString());
assert.equal(authorize.searchParams.get('code_challenge_method'),'s256');
assert.equal(authorize.searchParams.get('code_challenge'),createHash('sha256').update(verifier).digest('base64url'));
const provider=await fetch(authorize,{redirect:'manual',signal:AbortSignal.timeout(30000)});
assert.equal(provider.status,302);
const google=new URL(provider.headers.get('location'));assert.equal(google.hostname,'accounts.google.com');
assert.equal(google.searchParams.get('redirect_uri'),'https://qleeedwnnfvmfjjymoco.supabase.co/auth/v1/callback');
const account=await fetch(google,{signal:AbortSignal.timeout(30000)});
const accountUrl=new URL(account.url), accountHtml=await account.text();
assert.equal(account.status,200);assert.equal(accountUrl.hostname,'accounts.google.com');
assert(!accountUrl.pathname.includes('/error'));
assert(!accountHtml.includes('redirect_uri_mismatch'));assert(!accountHtml.includes('invalid_client'));
const result={at:new Date().toISOString(),origin:release.origin,buttonEnabled:true,comingSoonRemoved:true,serverActionStatus:started.status,pkceCookieMatchesChallenge:true,requestedReturnPathPreserved:true,providerStatus:provider.status,googleStatus:account.status,googlePath:accountUrl.pathname,passed:true,scope:'HTTP form submission and public provider initiation only; no browser, account login, consent, account creation, or session callback completion'};
fs.writeFileSync(path.join(dir,'google-sign-in.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
